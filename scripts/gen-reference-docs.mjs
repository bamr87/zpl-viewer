// Renders the extension's VS Code `contributes` blocks from package.json into
// docs/reference/{commands,settings,keybindings}.md, so the command, setting and
// keybinding reference is generated from the one place that defines it instead
// of being copied by hand (bamr87 fleet docs framework, UPS-DOC-05).
//
//   node scripts/gen-reference-docs.mjs           rewrite the three files
//   node scripts/gen-reference-docs.mjs --check   exit 1 when any file is stale
//
// No dependencies: Node built-ins only.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join, relative } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'docs', 'reference');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const nlsPath = join(root, 'package.nls.json');
const nls = existsSync(nlsPath) ? JSON.parse(readFileSync(nlsPath, 'utf8')) : {};
const contributes = pkg.contributes ?? {};
const product = `*${pkg.displayName || pkg.name}*`;
const banner = '<!-- GENERATED by `npm run docs:reference` (scripts/gen-reference-docs.mjs) from package.json — do not edit by hand -->';

/** Resolve a `%key%` placeholder through package.nls.json. */
const localize = (value) => {
  const m = typeof value === 'string' && value.match(/^%(.+)%$/);
  return m && typeof nls[m[1]] === 'string' ? nls[m[1]] : value;
};

/** Make text safe inside one Markdown table cell. */
const cell = (text) =>
  String(text ?? '')
    .replace(/`#([\w.-]+)#`/g, '`$1`')
    .replace(/\r?\n/g, '<br>')
    .replace(/\|/g, '\\|')
    .trim();

const code = (value) => '`' + cell(value) + '`';
const json = (value) => code(JSON.stringify(value));
const table = (head, rows) => [
  `| ${head.join(' | ')} |`,
  `| ${head.map(() => '---').join(' | ')} |`,
  ...rows.map((r) => `| ${r.map((c) => (c === '' ? '—' : c)).join(' | ')} |`),
];
const page = (title, summary, body) => [banner, `# ${title}`, '', `> ${summary}`, '', ...body, ''].join('\n');

const commands = contributes.commands ?? [];
const titleOf = (id) => {
  const c = commands.find((x) => x.command === id);
  if (!c) {
    return code(id);
  }
  const title = localize(c.title);
  const category = localize(c.category);
  return category ? `${category}: ${title}` : title;
};

function renderCommands() {
  const menus = contributes.menus ?? {};
  const submenus = new Map((contributes.submenus ?? []).map((s) => [s.id, localize(s.label)]));
  const palette = new Map((menus.commandPalette ?? []).map((m) => [m.command, m.when]));
  const placedIn = (id) => {
    const where = [];
    for (const [menu, items] of Object.entries(menus)) {
      if (menu === 'commandPalette' || !items.some((m) => m.command === id)) {
        continue;
      }
      where.push(submenus.has(menu) ? `${submenus.get(menu)} submenu` : code(menu));
    }
    return where.join(', ');
  };
  const paletteOf = (c) => {
    let shown = 'always';
    if (palette.has(c.command)) {
      const when = palette.get(c.command);
      shown = when === 'false' ? 'hidden' : when ? `when ${code(when)}` : 'always';
    }
    return c.enablement ? `${shown}; enabled when ${code(c.enablement)}` : shown;
  };
  const rows = commands.map((c) => [cell(titleOf(c.command)), code(c.command), paletteOf(c), placedIn(c.command)]);
  return page(
    'Commands',
    `Every command the ${product} extension contributes, with its ID, when the Command Palette offers it and which menus show it, generated from \`package.json\` \`contributes.commands\`.`,
    rows.length ? table(['Command', 'ID', 'Command Palette', 'Menus'], rows) : ['This extension contributes no commands.'],
  );
}

/** Type, default and the description cell of one configuration property. */
function describeSetting(spec) {
  const type = Array.isArray(spec.type) ? spec.type.join(' \\| ') : spec.type ?? '';
  const parts = [cell(localize(spec.markdownDescription ?? spec.description ?? ''))];
  if (Array.isArray(spec.enum)) {
    const notes = spec.markdownEnumDescriptions ?? spec.enumDescriptions ?? [];
    const options = spec.enum.map((v, i) => (notes[i] ? `${json(v)}: ${cell(localize(notes[i]))}` : json(v)));
    parts.push(notes.length ? `Allowed:<br>${options.join('<br>')}` : `Allowed: ${options.join(', ')}.`);
  }
  if (spec.minimum !== undefined || spec.maximum !== undefined) {
    parts.push(`Range: ${spec.minimum ?? '−∞'} to ${spec.maximum ?? '∞'}.`);
  }
  if (spec.scope) {
    parts.push(`Scope: ${code(spec.scope)}.`);
  }
  return {
    type: type ? code(type) : '',
    def: spec.default === undefined ? '' : json(spec.default),
    text: parts.filter(Boolean).join(' '),
  };
}

function renderSettings() {
  const raw = contributes.configuration;
  const sections = (Array.isArray(raw) ? raw : raw ? [raw] : []).filter((s) => s && s.properties);
  const body = [];
  const deprecated = [];
  const nested = [];
  for (const section of sections) {
    const rows = [];
    for (const [key, spec] of Object.entries(section.properties)) {
      const d = describeSetting(spec);
      const message = spec.markdownDeprecationMessage ?? spec.deprecationMessage;
      if (message) {
        deprecated.push([code(key), d.type, d.def, cell(localize(message))]);
        continue;
      }
      rows.push([code(key), d.type, d.def, d.text]);
      const shape = spec.type === 'array' ? spec.items : spec;
      if (shape && shape.properties) {
        const required = new Set(shape.required ?? []);
        const fields = Object.entries(shape.properties).map(([name, field]) => {
          const f = describeSetting(field);
          return [code(name) + (required.has(name) ? ' (required)' : ''), f.type, f.def, f.text];
        });
        nested.push(`### ${code(key)} ${spec.type === 'array' ? 'entries' : 'fields'}`, '', ...table(['Field', 'Type', 'Default', 'Description'], fields), '');
      }
    }
    if (sections.length > 1 && section.title) {
      body.push(`## ${localize(section.title)}`, '');
    }
    body.push(...table(['Setting', 'Type', 'Default', 'Description'], rows), '');
  }
  if (nested.length) {
    body.push('## Object settings', '', ...nested);
  }
  if (deprecated.length) {
    body.push('## Deprecated settings', '', ...table(['Setting', 'Type', 'Default', 'Deprecation'], deprecated), '');
  }
  return page(
    'Settings',
    `Every setting the ${product} extension contributes, with its type, default and allowed values, generated from \`package.json\` \`contributes.configuration\`.`,
    body.length ? body.slice(0, -1) : ['This extension contributes no settings.'],
  );
}

function renderKeybindings() {
  const bindings = contributes.keybindings ?? [];
  const extra = ['linux', 'win'].filter((os) => bindings.some((b) => b[os]));
  const head = ['Key', 'macOS', ...extra.map((os) => (os === 'win' ? 'Windows' : 'Linux')), 'Command', 'When'];
  const rows = bindings.map((b) => {
    const removes = b.command.startsWith('-');
    const id = removes ? b.command.slice(1) : b.command;
    let command = `${cell(titleOf(id))} (${code(id)})`;
    if (removes) {
      command = `removes the default binding of ${command}`;
    }
    if (b.args !== undefined) {
      command += ` with args ${json(b.args)}`;
    }
    return [code(b.key), code(b.mac ?? b.key), ...extra.map((os) => code(b[os] ?? b.key)), command, b.when ? code(b.when) : ''];
  });
  return page(
    'Keybindings',
    `Every default keyboard shortcut the ${product} extension contributes, with the command it runs and when it is active, generated from \`package.json\` \`contributes.keybindings\`.`,
    rows.length ? table(head, rows) : ['This extension contributes no keybindings.'],
  );
}

const outputs = {
  'commands.md': renderCommands(),
  'settings.md': renderSettings(),
  'keybindings.md': renderKeybindings(),
};

const check = process.argv.includes('--check');
const stale = [];
for (const [name, text] of Object.entries(outputs)) {
  const file = join(outDir, name);
  // Compare without line endings: a Windows checkout with core.autocrlf gets CRLF.
  const current = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
  if (current === text) {
    continue;
  }
  if (check) {
    stale.push(relative(root, file));
  } else {
    mkdirSync(outDir, { recursive: true });
    writeFileSync(file, text);
    console.log(`wrote ${relative(root, file)}`);
  }
}
if (stale.length) {
  console.error(`stale generated reference: ${stale.join(', ')} — run \`npm run docs:reference\``);
  process.exit(1);
}
